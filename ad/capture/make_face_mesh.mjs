// Builds ad/data/face_mesh.js for the ad's face-scan shot (ad tooling only, never shipped).
//   node ad/capture/make_face_mesh.mjs <path to canonical_face_model.obj>
// - 468 vertices of MediaPipe's generic canonical face model (Apache-2.0,
//   github.com/google-ai-edge/mediapipe, mediapipe/modules/face_geometry/data/). It is a
//   generic mesh, not a scan of a real person.
// - 10 iris points (468-477) placed from the eye contours, as Face Landmarker returns 478.
// - Connection lists exported by @mediapipe/tasks-vision (FaceLandmarker.FACE_LANDMARKS_*).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ad = dirname(here)
const objPath = process.argv[2]
const { FaceLandmarker: F } = await import(join(ad, '..', 'web', 'node_modules', '@mediapipe', 'tasks-vision', 'vision_bundle.mjs'))

const v = readFileSync(objPath, 'utf8').split('\n').filter((l) => l.startsWith('v ')).map((l) => l.trim().split(/\s+/).slice(1).map(Number))
if (v.length !== 468) throw new Error(`expected 468 vertices, got ${v.length}`)

const pairs = (list) => list.map((c) => [c.start, c.end])
const ids = (list) => [...new Set(list.flatMap((c) => [c.start, c.end]))]
const mean = (is) => [0, 1, 2].map((k) => is.reduce((s, i) => s + v[i][k], 0) / is.length)

// Iris: centre of each eye contour, four points around it (right, top, left, bottom).
const iris = (eye) => {
  const e = ids(eye)
  const c = mean(e)
  const xs = e.map((i) => v[i][0])
  const r = (Math.max(...xs) - Math.min(...xs)) * 0.21
  return [c, [c[0] + r, c[1], c[2]], [c[0], c[1] + r, c[2]], [c[0] - r, c[1], c[2]], [c[0], c[1] - r, c[2]]]
}
const pts = [...v, ...iris(F.FACE_LANDMARKS_RIGHT_EYE), ...iris(F.FACE_LANDMARKS_LEFT_EYE)].map((p) => p.map((x) => Math.round(x * 1000) / 1000))

const out = {
  source: 'MediaPipe canonical_face_model.obj (Apache-2.0) + @mediapipe/tasks-vision connection lists',
  points: pts,
  tesselation: pairs(F.FACE_LANDMARKS_TESSELATION),
  contours: pairs(F.FACE_LANDMARKS_CONTOURS),
  rightEye: pairs(F.FACE_LANDMARKS_RIGHT_EYE),
  leftEye: pairs(F.FACE_LANDMARKS_LEFT_EYE),
  rightIris: pairs(F.FACE_LANDMARKS_RIGHT_IRIS),
  leftIris: pairs(F.FACE_LANDMARKS_LEFT_IRIS),
}
mkdirSync(join(ad, 'data'), { recursive: true })
writeFileSync(join(ad, 'data', 'face_mesh.js'),
  '// Generated by ad/capture/make_face_mesh.mjs. Generic MediaPipe canonical face model (Apache-2.0), not a real person.\n' +
  `window.FACE_MESH = ${JSON.stringify(out)}\n`)
console.log('points', pts.length, 'tess', out.tesselation.length, 'contours', out.contours.length)

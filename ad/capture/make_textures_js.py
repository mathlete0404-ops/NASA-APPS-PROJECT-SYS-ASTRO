"""Wraps ad/textures/*.jpg as data URLs in ad/textures/textures.js (ad tooling only).
WebGL cannot read images from file:// pages, so the ad loads its planet maps from this
script; that keeps ad/index.html working when opened straight from disk."""
import base64, os
D = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'textures')
parts = []
for n in ('earth_day', 'earth_clouds', 'moon', 'mars'):
    b = base64.b64encode(open(os.path.join(D, n + '.jpg'), 'rb').read()).decode()
    parts.append(f'  {n}: "data:image/jpeg;base64,{b}"')
open(os.path.join(D, 'textures.js'), 'w').write('// Generated by ad/capture/make_textures_js.py from the .jpg files in this folder (sources: README References).\nwindow.TEXTURES = {\n' + ',\n'.join(parts) + '\n}\n')
